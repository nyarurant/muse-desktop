'use strict';
const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('muse',Object.freeze({
  info:()=>ipcRenderer.invoke('muse:info'),
  connect:()=>ipcRenderer.invoke('muse:connect'),
  login:()=>ipcRenderer.invoke('muse:login'),
  importCapture:()=>ipcRenderer.invoke('muse:import'),
  sessions:()=>ipcRenderer.invoke('muse:sessions'),
  subscribe:id=>ipcRenderer.invoke('muse:subscribe',id),
  history:(id,before)=>ipcRenderer.invoke('muse:history',id,before),
  send:(text,id,extra)=>ipcRenderer.invoke('muse:send',text,id,extra),
  cancel:id=>ipcRenderer.invoke('muse:cancel',id),
  startSession:()=>ipcRenderer.invoke('muse:new-session'),
  archivedSessions:()=>ipcRenderer.invoke('muse:archived-sessions'),
  sessionAction:(id,action)=>ipcRenderer.invoke('muse:session-action',id,action),
  renameSession:(id,title)=>ipcRenderer.invoke('muse:rename-session',id,title),
  markSeen:id=>ipcRenderer.invoke('muse:mark-seen',id),
  search:query=>ipcRenderer.invoke('muse:search',query),
  react:(messageId,emoji)=>ipcRenderer.invoke('muse:react',messageId,emoji),
  deleteMessage:messageId=>ipcRenderer.invoke('muse:delete-message',messageId),
  tasks:()=>ipcRenderer.invoke('muse:tasks'),
  feed:()=>ipcRenderer.invoke('muse:feed'),
  ideas:()=>ipcRenderer.invoke('muse:ideas'),
  goals:()=>ipcRenderer.invoke('muse:goals'),
  library:(preset,offset)=>ipcRenderer.invoke('muse:library',preset,offset),
  image:ref=>ipcRenderer.invoke('muse:image',ref),
  saveFile:p=>ipcRenderer.invoke('muse:save-file',p),
  approvals:()=>ipcRenderer.invoke('muse:approvals'),
  decide:(id,decision)=>ipcRenderer.invoke('muse:decide',id,decision),
  autoResume:()=>ipcRenderer.invoke('muse:auto-resume'),
  setAutoResume:enabled=>ipcRenderer.invoke('muse:set-auto-resume',enabled),
  approvalMode:()=>ipcRenderer.invoke('muse:approval-mode'),
  setApprovalMode:mode=>ipcRenderer.invoke('muse:set-approval-mode',mode),
  identity:()=>ipcRenderer.invoke('muse:identity'),
  avatar:imagePath=>ipcRenderer.invoke('muse:avatar',imagePath),
  themes:()=>ipcRenderer.invoke('muse:themes'),
  activity:()=>ipcRenderer.invoke('muse:activity'),
  openTools:()=>ipcRenderer.invoke('muse:tools'),
  openLink:url=>ipcRenderer.invoke('muse:open-link',url),
  renderMarkdown:text=>ipcRenderer.invoke('muse:markdown',text),
  onEvent:callback=>{const listener=(_,value)=>callback(value);ipcRenderer.on('muse:event',listener);return()=>ipcRenderer.removeListener('muse:event',listener);},
}));
